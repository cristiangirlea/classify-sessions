// Generates src/api/contract.gen.ts from ../contract/*.schema.json.
// `--check` regenerates in memory and exits 1 if the committed file differs.
import { compileFromFile } from 'json-schema-to-typescript';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const contractDir = join(here, '..', '..', 'contract');
const outFile = join(here, '..', 'src', 'api', 'contract.gen.ts');
const opts = { cwd: contractDir, bannerComment: '', additionalProperties: false, format: true };

// summary.schema.json pulls in ModelsResponse through its $ref, so models is not compiled twice.
const parts = [];
for (const name of ['summary.schema.json', 'error.schema.json']) {
  parts.push(await compileFromFile(join(contractDir, name), opts));
}
const banner = '// Generated by `npm run contract:gen` from contract/*.schema.json. Do not edit.\n\n';
const text = (banner + parts.join('\n')).replace(/\r\n/g, '\n');

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n'); } catch {}
  if (current !== text) {
    console.error('contract.gen.ts is stale: run `npm run contract:gen`');
    process.exit(1);
  }
  console.log('contract.gen.ts matches contract/');
} else {
  writeFileSync(outFile, text);
  console.log('wrote src/api/contract.gen.ts');
}
